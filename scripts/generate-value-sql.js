#!/usr/bin/env node
// Generates sql/extract_values.sql: collects the distinct stored values of every
// value column (scripts/lib/value-columns.js) so BuildPrompt can recognise them
// in questions. Read-only; uses one #temp table (any login may create those).
//
//   1. node scripts/generate-value-sql.js          (after a catalog change)
//   2. Run sql/extract_values.sql in SSMS as the NLSQL read-only login and save the
//      result grid as CSV (enable "Quote strings containing list separators").
//   3. node scripts/build-value-index.js --input values.csv   -> catalog/values.json
//
// Columns with more than --max-distinct distinct values (default 5000) are skipped
// in SQL: free-text-like columns would only add noise and size.
//
// Usage: node scripts/generate-value-sql.js [--max-distinct <n>] [--check]

const fs = require('fs');
const path = require('path');
const { loadCatalogs } = require('./lib/catalog-loader');
const { valueColumns } = require('./lib/value-columns');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'sql', 'extract_values.sql');
const DEFAULT_MAX_DISTINCT = 5000;

const lit = (s) => `N'${String(s).replace(/'/g, "''")}'`;
const ident = (s) => `[${String(s).replace(/\]/g, ']]')}]`;

function columnBlock(vc, maxDistinct) {
  const c = ident(vc.column);
  const keyExpr = vc.key
    ? `CASE WHEN COUNT(DISTINCT ${ident(vc.key)}) = 1 THEN CAST(MIN(${ident(vc.key)}) AS nvarchar(100)) END`
    : 'CAST(NULL AS nvarchar(100))';
  return `BEGIN TRY
  IF (SELECT COUNT(DISTINCT ${c}) FROM ${vc.source}) <= ${maxDistinct}
    INSERT INTO #nlsql_values (entity, [column], value, [rows], key_value)
    SELECT ${lit(vc.entity)}, ${lit(vc.column)}, CAST(${c} AS nvarchar(400)), COUNT(*), ${keyExpr}
    FROM ${vc.source} WHERE ${c} IS NOT NULL AND LTRIM(RTRIM(CAST(${c} AS nvarchar(400)))) <> N'' GROUP BY ${c};
  ELSE PRINT N'skipped (more than ${maxDistinct} distinct values): ${vc.entity}.${vc.column.replace(/'/g, "''")}';
END TRY
BEGIN CATCH PRINT N'FAILED ${vc.entity}.${vc.column.replace(/'/g, "''")}: ' + ERROR_MESSAGE(); END CATCH`;
}

function generate(catalogs, { maxDistinct = DEFAULT_MAX_DISTINCT } = {}) {
  const cols = valueColumns(catalogs.map((c) => c.data).filter(Boolean));
  return `-- Generated by scripts/generate-value-sql.js from the catalog JSON files - do not edit by hand.
-- Run in SSMS AS THE NLSQL READ-ONLY LOGIN, in the warehouse database. Read-only (one #temp table).
-- Then save the result grid as CSV and run: node scripts/build-value-index.js --input <file.csv>
-- The result is real warehouse data (names of customers, suppliers, staff): keep the CSV and
-- catalog/values.json out of git.
-- ${cols.length} columns; columns with more than ${maxDistinct} distinct values are skipped (see Messages).
SET NOCOUNT ON;
IF OBJECT_ID(N'tempdb..#nlsql_values') IS NOT NULL DROP TABLE #nlsql_values;
CREATE TABLE #nlsql_values (entity nvarchar(128), [column] nvarchar(128), value nvarchar(400), [rows] bigint, key_value nvarchar(100));
${cols.map((vc) => columnBlock(vc, maxDistinct)).join('\n')}
SELECT entity, [column], value, [rows], key_value FROM #nlsql_values ORDER BY entity, [column], [rows] DESC;
DROP TABLE #nlsql_values;
`;
}

function parseArgs(argv) {
  const args = { maxDistinct: DEFAULT_MAX_DISTINCT, check: false };
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === '--max-distinct') args.maxDistinct = Number(argv[++i]);
    else if (argv[i] === '--check') args.check = true;
    else throw new Error(`Unknown argument: ${argv[i]}`);
  }
  if (!Number.isInteger(args.maxDistinct) || args.maxDistinct < 1) throw new Error('--max-distinct must be a positive integer');
  return args;
}

function main() {
  const args = parseArgs(process.argv.slice(2));
  const text = generate(loadCatalogs(path.join(ROOT, 'catalog')), args);
  if (args.check) {
    const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (current !== text) {
      console.error('sql/extract_values.sql is stale. Run: node scripts/generate-value-sql.js');
      process.exit(1);
    }
    console.log('sql/extract_values.sql is up to date.');
    return;
  }
  fs.writeFileSync(OUT, text);
  console.log(`Wrote ${path.relative(ROOT, OUT)}`);
}

if (require.main === module) main();

module.exports = { generate, OUT, DEFAULT_MAX_DISTINCT };
