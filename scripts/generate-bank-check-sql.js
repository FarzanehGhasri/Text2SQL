#!/usr/bin/env node
// Generates sql/check_query_bank.sql: every few-shot example (catalog examples
// + catalog/query_bank.json) exactly as it would run in production - passed
// through the real Security node, so wrapped in the entity CTEs and capped at
// TOP 200. Run it once in SSMS as the read-only login after adding examples:
// an example that errors teaches the model broken SQL; one whose result looks
// right can be marked "status": "verified" in the bank.
//
// Usage: node scripts/generate-bank-check-sql.js            # (re)write the file
//        node scripts/generate-bank-check-sql.js --check    # exit 1 if it is stale

const fs = require('fs');
const path = require('path');
const { loadCatalogs } = require('./lib/catalog-loader');
const { loadQueryBank, allExamples } = require('./lib/query-bank');
const { runCodeNode } = require('./lib/n8n-code-runner');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'sql', 'check_query_bank.sql');

// Every entity of every catalog, with exposed columns only - the same shape
// BuildPrompt hands to Security as entityDefs.
function allEntityDefs(catalogs) {
  const defs = {};
  for (const c of catalogs) {
    for (const e of c.entities || []) {
      defs[e.name] = {
        name: e.name, kind: e.kind || 'table', source: e.source || null, sql: e.sql || null,
        columns: (e.columns || []).filter((col) => col.exposed !== false).map((col) => ({ name: col.name, alias: col.alias || null })),
      };
    }
  }
  return defs;
}

// The final SQL Security would send to SQL Server for this example (throws on a rejection).
function securedSql(sql, entityDefs) {
  const { json } = runCodeNode('Security', {
    inputs: [{ response: `UNDERSTOOD: example\nSQL:\n${sql}` }],
    nodes: { BuildPrompt: { entityDefs } },
  });
  return json.sql;
}

const lit = (s) => `N'${String(s).replace(/'/g, "''").replace(/\r?\n/g, ' ')}'`;

function generate(catalogs, bank) {
  const defs = allEntityDefs(catalogs);
  const blocks = allExamples(catalogs, bank).map((ex) =>
    `PRINT ${lit(`${ex.id} | ${ex.q}`)};\n${securedSql(ex.sql, defs)};\nGO`);
  return `-- Generated by scripts/generate-bank-check-sql.js from catalog examples and catalog/query_bank.json - do not edit by hand.
-- Run in SSMS AS THE NLSQL READ-ONLY LOGIN, in the warehouse database. Read-only.
-- Every example is its own batch (GO), so a broken one does not stop the rest. In the Messages tab each
-- example prints "<id> | <question>" first: an error right after an id means that example is wrong -
-- fix it in catalog/query_bank.json (or the catalog's "examples"). When a result looks right for its
-- question, set "status": "verified" on that example.
SET NOCOUNT ON;
GO
${blocks.join('\n')}
`;
}

function load() {
  const catalogs = loadCatalogs(path.join(ROOT, 'catalog')).filter((c) => c.data).map((c) => c.data);
  const bank = loadQueryBank(path.join(ROOT, 'catalog'));
  return { catalogs, bank: bank && bank.data };
}

function main() {
  const { catalogs, bank } = load();
  const text = generate(catalogs, bank);
  if (process.argv[2] === '--check') {
    const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (current !== text) {
      console.error('sql/check_query_bank.sql is stale. Run: node scripts/generate-bank-check-sql.js');
      process.exit(1);
    }
    console.log('sql/check_query_bank.sql is up to date.');
    return;
  }
  fs.writeFileSync(OUT, text);
  console.log(`Wrote ${path.relative(ROOT, OUT)}`);
}

if (require.main === module) main();

module.exports = { generate, load, allEntityDefs, securedSql, OUT };
