#!/usr/bin/env node
// Writes the catalogs into the Obsidian vault as linked notes, so the schema
// can be browsed, searched and graphed in Obsidian:
//   obsidian/Catalog/<domain>/<domain>.md   domain overview: hints, examples, tables
//   obsidian/Catalog/<domain>/<Entity>.md   one note per table: columns, joins as [[links]]
//
// The catalog JSON stays the source of truth: these notes are regenerated on
// every run and carry a "generated" marker. Put your own notes about a table
// in obsidian/Catalog Notes/ and link to the generated note instead.
//
// Usage (from the repo root):
//   node scripts/export-catalog-to-obsidian.js            # (re)write the notes
//   node scripts/export-catalog-to-obsidian.js --check    # exit 1 if they are stale

const fs = require('fs');
const path = require('path');
const { loadCatalogs } = require('./lib/catalog-loader');

const ROOT = path.join(__dirname, '..');
const OUT_DIR = path.join(ROOT, 'obsidian', 'Catalog');
const MARKER = '<!-- generated by scripts/export-catalog-to-obsidian.js - edit catalog/*.json instead -->';

const cell = (s) => String(s == null ? '' : s).replace(/\|/g, '\\|').replace(/\n/g, ' ');
const yamlStr = (s) => JSON.stringify(String(s));

function entityNote(ent, cat, joinsFrom, joinsTo) {
  const cols = ent.columns || [];
  const review = cols.filter((c) => c.review && c.exposed !== false).length;
  const lines = [
    '---',
    'type: table',
    `domain: ${cat.domain}`,
    `source: ${yamlStr(ent.source || '')}`,
    `core: ${Boolean(ent.core)}`,
    `shared: ${Boolean(cat.shared)}`,
    `columns: ${cols.length}`,
    `hidden_columns: ${cols.filter((c) => c.exposed === false).length}`,
    `review_columns: ${review}`,
    `synonyms: [${(ent.synonyms_fa || []).map(yamlStr).join(', ')}]`,
    `tags: [catalog, domain/${cat.domain}${ent.core ? ', core' : ''}${review ? ', needs-review' : ''}]`,
    '---',
    MARKER,
    `# ${ent.name}`,
    '',
    `> ${ent.description_fa || ''}`,
    '',
    `- **Domain:** [[${cat.domain}]]${cat.shared ? ' (shared dimension catalog)' : ''}`,
    `- **Physical source:** \`${ent.source || ''}\``,
    ent.core ? '- **Core table** of its domain: always in the prompt when the domain is active' : null,
    (ent.synonyms_fa || []).length ? `- **Synonyms:** ${ent.synonyms_fa.join('، ')}` : '- **Synonyms:** none - keyword retrieval only sees the name and description',
    '',
    '## Columns',
    '',
    '| Column | Type | Description | Flags |',
    '|---|---|---|---|',
    ...cols.map((c) => {
      const flags = [c.exposed === false ? 'hidden' : '', c.review ? '⚠️ review' : '', c.alias ? `alias: ${c.alias}` : '']
        .filter(Boolean).join(', ');
      return `| \`${cell(c.name)}\` | ${cell(c.type)} | ${cell(c.description_fa)} | ${cell(flags)} |`;
    }),
    '',
    '## Joins',
    '',
    joinsFrom.length ? '**References** (this table → dimension):' : '**References:** none',
    ...joinsFrom.map((j) => `- \`${j.from_column}\` → [[${j.to}]].\`${j.to_column}\``),
    '',
    joinsTo.length ? '**Referenced by:**' : '**Referenced by:** none',
    ...joinsTo.map((j) => `- [[${j.from}]].\`${j.from_column}\` → \`${j.to_column}\``),
    '',
  ];
  return lines.filter((l) => l !== null).join('\n');
}

function domainNote(cat) {
  const ents = cat.entities || [];
  return [
    '---',
    'type: domain',
    `domain: ${cat.domain}`,
    `shared: ${Boolean(cat.shared)}`,
    `tables: ${ents.length}`,
    `tags: [catalog, domain/${cat.domain}]`,
    '---',
    MARKER,
    `# ${cat.domain}`,
    '',
    `> ${cat.description_fa || ''}`,
    '',
    '## Access (AD groups)',
    ...Object.entries(cat.permissions || {}).map(([g, l]) => `- \`${g}\`: ${l.includes('*') ? 'all tables' : l.join(', ')}`),
    '',
    '## Domain hints sent to the model',
    ...((cat.hints_fa || []).length
      ? cat.hints_fa.map((h) => (typeof h === 'string' ? `- ${h}` : `- ${h.text} _(only with ${h.entities.map((e) => `[[${e}]]`).join(', ')})_`))
      : ['- none']),
    '',
    '## Examples sent to the model',
    ...((cat.examples || []).length
      ? cat.examples.flatMap((ex) => [`- **${ex.q}**`, '  ```sql', `  ${ex.sql}`, '  ```'])
      : ['- none']),
    '',
    '## Tables',
    '| Table | Description | Core |',
    '|---|---|---|',
    ...ents.map((e) => `| [[${e.name}]] | ${cell(e.description_fa)} | ${e.core ? '⭐' : ''} |`),
    '',
  ].join('\n');
}

// { relativePath: content } for every note.
function render(catalogs) {
  const joins = catalogs.flatMap((c) => c.joins || []);
  const files = {};
  for (const cat of catalogs) {
    files[path.join(cat.domain, `${cat.domain}.md`)] = domainNote(cat);
    for (const ent of cat.entities || []) {
      files[path.join(cat.domain, `${ent.name}.md`)] = entityNote(
        ent, cat,
        joins.filter((j) => j.from === ent.name),
        joins.filter((j) => j.to === ent.name)
      );
    }
  }
  return files;
}

// Generated notes currently on disk (identified by the marker), relative paths.
function existingGenerated(dir) {
  if (!fs.existsSync(dir)) return [];
  const out = [];
  const walk = (d) => {
    for (const f of fs.readdirSync(d, { withFileTypes: true })) {
      const p = path.join(d, f.name);
      if (f.isDirectory()) walk(p);
      else if (f.name.endsWith('.md') && fs.readFileSync(p, 'utf8').includes(MARKER)) out.push(path.relative(dir, p));
    }
  };
  walk(dir);
  return out;
}

function main() {
  const catalogs = loadCatalogs(path.join(ROOT, 'catalog')).filter((c) => c.data).map((c) => c.data);
  const files = render(catalogs);
  const stale = existingGenerated(OUT_DIR).filter((f) => !(f in files));

  if (process.argv[2] === '--check') {
    const changed = Object.entries(files).filter(([f, text]) => {
      const p = path.join(OUT_DIR, f);
      return !fs.existsSync(p) || fs.readFileSync(p, 'utf8') !== text;
    });
    if (changed.length || stale.length) {
      console.error(`obsidian/Catalog is stale (${changed.length} changed, ${stale.length} to remove). Run: node scripts/export-catalog-to-obsidian.js`);
      process.exit(1);
    }
    console.log('obsidian/Catalog is up to date.');
    return;
  }

  for (const [f, text] of Object.entries(files)) {
    fs.mkdirSync(path.dirname(path.join(OUT_DIR, f)), { recursive: true });
    fs.writeFileSync(path.join(OUT_DIR, f), text);
  }
  // only files this script generated are ever removed
  for (const f of stale) fs.unlinkSync(path.join(OUT_DIR, f));
  console.log(`Wrote ${Object.keys(files).length} notes to obsidian/Catalog${stale.length ? `, removed ${stale.length} stale` : ''}.`);
}

if (require.main === module) main();

module.exports = { render, MARKER, OUT_DIR };
