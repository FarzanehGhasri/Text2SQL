#!/usr/bin/env node
// Generates sql/verify_catalog_access.sql from catalog/*.json: a read-only
// check to run in SSMS *as the NLSQL login*, in the warehouse database, after
// pointing n8n at a server. It lists every problem the workflow would hit at
// query time:
//   - a catalog source table/view that does not exist
//   - a source the login cannot SELECT from
//   - a catalog column that does not exist in its source (hidden columns are
//     checked too, so schema drift shows up before anyone exposes them)
//   - database-level write permissions the login should not have
// An empty result set means the catalogs and the login are ready.
//
// Usage: node scripts/generate-verify-sql.js            # (re)write the file
//        node scripts/generate-verify-sql.js --check    # exit 1 if it is stale

const fs = require('fs');
const path = require('path');
const { loadCatalogs } = require('./lib/catalog-loader');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'sql', 'verify_catalog_access.sql');

const q = (s) => `N'${String(s).replace(/'/g, "''")}'`;

function generate(catalogs) {
  const rows = [];
  for (const { data } of catalogs) {
    for (const e of (data && data.entities) || []) {
      if ((e.kind || 'table') !== 'table') continue;
      for (const c of e.columns || []) rows.push(`(${q(e.name)}, ${q(e.source)}, ${q(c.name)})`);
    }
  }
  // Line comments only: T-SQL block comments nest, so the "/*" in "catalog/*.json"
  // inside a /* ... */ header would leave the comment unterminated.
  return `-- Generated by scripts/generate-verify-sql.js from the catalog JSON files - do not edit by hand.
-- Run in SSMS while connected AS THE NLSQL READ-ONLY LOGIN, in the warehouse database
-- (the n8n "Microsoft SQL account" credential's database). Read-only: it only reads
-- metadata. An empty result means every catalog table and column exists, the login
-- can SELECT every source, and the login has no database-level write permission.
SET NOCOUNT ON;

WITH catalog_columns (entity, source, col) AS (
  SELECT entity, source, col FROM (VALUES
    ${rows.join(',\n    ')}
  ) AS v (entity, source, col)
),
sources AS (
  SELECT DISTINCT entity, source FROM catalog_columns
)
SELECT problem, entity, source, col FROM (
  SELECT N'source does not exist' AS problem, entity, source, CAST(NULL AS nvarchar(128)) AS col
  FROM sources WHERE OBJECT_ID(source) IS NULL
  UNION ALL
  SELECT N'login cannot SELECT from source', entity, source, NULL
  FROM sources WHERE OBJECT_ID(source) IS NOT NULL AND HAS_PERMS_BY_NAME(source, 'OBJECT', 'SELECT') = 0
  UNION ALL
  SELECT N'column does not exist', entity, source, col
  FROM catalog_columns WHERE OBJECT_ID(source) IS NOT NULL AND COL_LENGTH(source, col) IS NULL
  UNION ALL
  SELECT N'login has database-level ' + p.perm + N' permission (should be read-only)', NULL, DB_NAME(), NULL
  FROM (VALUES (N'INSERT'), (N'UPDATE'), (N'DELETE'), (N'ALTER'), (N'CREATE TABLE'), (N'EXECUTE')) AS p (perm)
  WHERE HAS_PERMS_BY_NAME(DB_NAME(), 'DATABASE', p.perm) = 1
) AS problems
ORDER BY problem, entity, col;
`;
}

function main() {
  const text = generate(loadCatalogs(path.join(ROOT, 'catalog')));
  if (process.argv[2] === '--check') {
    const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (current !== text) {
      console.error('sql/verify_catalog_access.sql is stale. Run: node scripts/generate-verify-sql.js');
      process.exit(1);
    }
    console.log('sql/verify_catalog_access.sql is up to date.');
    return;
  }
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, text);
  console.log(`Wrote ${path.relative(ROOT, OUT)}`);
}

if (require.main === module) main();

module.exports = { generate, OUT };
